test('checksum mismatch aborts without downloading an artifact', async () => {
  await withTempDir(async (base) => {
    const artifact = path.join(base, 'artifact.bin');
    await writeFile(artifact, 'pinned generator bytes\n');

    await assert.rejects(
      () => verifySha256(artifact, '0'.repeat(64), 'fixture artifact'),
      /checksum/i,
    );
    await verifySha256(
      artifact,
      '9c3c90726aa585fd3a48524058be29aa336569d8ac9989361fd55d77edbeeabb',
      'fixture artifact',
    );
  });
});

test('two clean generations have identical relative paths and bytes', async () => {
  await withTempDir(async (base) => {
    const first = path.join(base, 'first');
    const second = path.join(base, 'second');
    await generateAll(first);
    await generateAll(second);

    for (const boundary of ['java', 'typescript']) {
      assert.deepEqual(
        await listRelativeFiles(path.join(first, boundary)),
        await listRelativeFiles(path.join(second, boundary)),
        `${boundary} relative path list changed between clean runs`,
      );
      await compareTrees(path.join(first, boundary), path.join(second, boundary));
    }
  });
});

test('generated transport models do not substitute any/Object for contract schemas', async () => {
  await withTempDir(async (base) => {
    await generateAll(base);
    const modelsDir = path.join(base, 'typescript', 'models');
    const modelFiles = (await readdir(modelsDir)).filter(
      (name) => name.endsWith('.ts') && name !== 'index.ts',
    );
    assert.ok(modelFiles.length > 10, 'expected generated model files');

    for (const modelFile of modelFiles) {
      const source = await readFile(path.join(modelsDir, modelFile), 'utf8');
      const interfaces = [...source.matchAll(/export interface \w+ \{([\s\S]*?)\n\}/g)];
      assert.ok(
        interfaces.length > 0 || /export type \w+ =/.test(source),
        `${modelFile} should declare a contract type`,
      );
      for (const [, body] of interfaces) {
        assert.doesNotMatch(
          body,
          /^\s*\w+\??:\s*(any|Object)(\[\])?\s*;/m,
          `${modelFile} contains an unconstrained any/Object model property`,
        );
      }
      assert.doesNotMatch(
        source,
        /export type \w+ = (any|Object)(\[\])?;/,
        `${modelFile} aliases a contract schema to any/Object`,
      );
    }

    const cfpbCase = await readFile(path.join(modelsDir, 'CfpbCase.ts'), 'utf8');
    assert.match(cfpbCase, /analystNotes:\s*null;/);
    assert.match(cfpbCase, /subProduct:\s*string \| null;/);

    const analystCase = await readFile(path.join(modelsDir, 'AnalystCase.ts'), 'utf8');
    assert.match(analystCase, /provenance:\s*null;/);
  });
});

test('generated multipart import uses a JSON Blob and leaves boundary management to transport', async () => {
  await withTempDir(async (base) => {
    await generateAll(base);
    const apiSource = await readFile(
      path.join(base, 'typescript', 'apis', 'ImportsApi.ts'),
      'utf8',
    );

    assert.match(apiSource, /new FormData\(\)/);
    assert.match(apiSource, /formParams\.append\('file', requestParameters\['file'\] as any\)/);
    assert.match(
      apiSource,
      /new Blob\(\[JSON\.stringify\(ImportMetadataToJSON\(requestParameters\['metadata'\]\)\)\], \{ type: "application\/json", \}\)/,
    );
    assert.doesNotMatch(apiSource, /boundary/i);
    assert.doesNotMatch(apiSource, /headers?\[['"]Content-Type['"]\]\s*=\s*['"]multipart\/form-data/i);
  });
});

test('generated Java interfaces are abstract and contain no default endpoint implementations', async () => {
  await withTempDir(async (base) => {
    await generateAll(base);
    const apiDir = path.join(
      base,
      'java',
      'src',
      'main',
      'java',
      'id',
      'ac',
      'finresolve',
      'api',
    );
    const interfaces = (await readdir(apiDir)).filter((name) => name.endsWith('Api.java'));
    assert.deepEqual(interfaces.sort(), [
      'CasesApi.java',
      'CategoriesApi.java',
      'ImportsApi.java',
      'SearchApi.java',
      'SystemApi.java',
    ]);

    for (const interfaceFile of interfaces) {
      const source = await readFile(path.join(apiDir, interfaceFile), 'utf8');
      assert.doesNotMatch(source, /\bdefault\s+ResponseEntity</, `${interfaceFile} has a default endpoint`);
    }
  });
});

test('Maven plugin consumes the shared Java generator configuration', async () => {
  const pom = await readFile(path.join(repoRoot, 'backend', 'pom.xml'), 'utf8');
  assert.ok(
    pom.includes(
      '<configurationFile>${project.basedir}/../tools/openapi/java.json</configurationFile>',
    ),
    'backend/pom.xml must load tools/openapi/java.json',
  );
  assert.doesNotMatch(pom, /<configOptions>/, 'generator options must stay in java.json');
  assert.doesNotMatch(pom, /<typeMappings>/, 'type mappings must stay in java.json');
  assert.doesNotMatch(
    pom,
    /<(apiPackage|modelPackage|invokerPackage)>/,
    'package options must stay in java.json',
  );

  const javaOptions = JSON.parse(
    await readFile(path.join(here, 'java.json'), 'utf8'),
  );
  assert.equal(javaOptions.generatorName, 'spring');
  assert.ok(
    pom.includes(`<generatorName>${javaOptions.generatorName}</generatorName>`),
    'Maven generator name must match java.json',
  );
  assert.equal(javaOptions.typeMappings.null, 'Void');

  const toolchain = await loadToolchain();
  assert.equal(
    path.resolve(repoRoot, toolchain.templates.java),
    path.join(repoRoot, 'backend', 'src', 'main', 'resources', 'openapi-templates'),
  );
  assert.ok(
    pom.includes(
      '<templateDirectory>${project.basedir}/src/main/resources/openapi-templates</templateDirectory>',
    ),
    'Maven template path must match the shared template directory',
  );
});

test('generated TypeScript uses ESM-safe .js relative imports', async () => {
  await withTempDir(async (base) => {
    await generateAll(base);
    const indexPath = path.join(base, 'typescript', 'index.ts');
    const casesPath = path.join(base, 'typescript', 'apis', 'CasesApi.ts');
    const index = await readFile(indexPath, 'utf8');
    const cases = await readFile(casesPath, 'utf8');

    assert.match(index, /from '\.\/runtime\.js'/);
    assert.match(cases, /from '\.\.\/runtime\.js'/);
    assert.doesNotMatch(cases, /from '\.\.\/runtime';/);
  });
});

test('api:check leaves tracked and untracked workspace state unchanged', async () => {
  const before = await execFileAsync(
    'git',
    ['status', '--porcelain=v1', '--untracked-files=all'],
    { cwd: repoRoot },
  );
  await execFileAsync(process.execPath, [path.join(here, 'check.mjs')], {
    cwd: repoRoot,
    maxBuffer: 64 * 1024 * 1024,
  });
  const after = await execFileAsync(
    'git',
    ['status', '--porcelain=v1', '--untracked-files=all'],
    { cwd: repoRoot },
  );

  assert.equal(after.stdout, before.stdout);
});

